//! Representative grammars used by the size report and the tests.

use crate::{Associativity, GrammarBuilder};

/// A tiny ambiguous expression grammar that only builds with precedence.
pub fn expr() -> GrammarBuilder {
    GrammarBuilder::new()
        .name("expr")
        .terminal("NUM")
        .terminal("NAME")
        .terminal("PLUS")
        .terminal("MINUS")
        .terminal("STAR")
        .terminal("SLASH")
        .terminal("LP")
        .terminal("RP")
        .precedence(1, Associativity::Left, &["PLUS", "MINUS"])
        .precedence(2, Associativity::Left, &["STAR", "SLASH"])
        .rule("expr", &["expr", "PLUS", "term"])
        .rule("expr", &["expr", "MINUS", "term"])
        .rule("expr", &["term"])
        .rule("term", &["term", "STAR", "factor"])
        .rule("term", &["term", "SLASH", "factor"])
        .rule("term", &["factor"])
        .rule("factor", &["MINUS", "factor"])
        .rule("factor", &["atom"])
        .rule("atom", &["NUM"])
        .rule("atom", &["NAME"])
        .rule("atom", &["LP", "expr", "RP"])
}

/// A JSON subset: the grammar a real language would hand the generator.
pub fn json() -> GrammarBuilder {
    GrammarBuilder::new()
        .name("json")
        .terminal("LBRACE")
        .terminal("RBRACE")
        .terminal("LBRACKET")
        .terminal("RBRACKET")
        .terminal("COLON")
        .terminal("COMMA")
        .terminal("STRING")
        .terminal("NUMBER")
        .terminal("TRUE")
        .terminal("FALSE")
        .terminal("NULL")
        .rule("document", &["value"])
        .rule("value", &["object"])
        .rule("value", &["array"])
        .rule("value", &["STRING"])
        .rule("value", &["NUMBER"])
        .rule("value", &["TRUE"])
        .rule("value", &["FALSE"])
        .rule("value", &["NULL"])
        .rule("object", &["LBRACE", "members", "RBRACE"])
        .rule("object", &["LBRACE", "RBRACE"])
        .rule("members", &["member"])
        .rule("members", &["members", "COMMA", "member"])
        .rule("member", &["STRING", "COLON", "value"])
        .rule("array", &["LBRACKET", "elements", "RBRACKET"])
        .rule("array", &["LBRACKET", "RBRACKET"])
        .rule("elements", &["value"])
        .rule("elements", &["elements", "COMMA", "value"])
}

/// A Python-shaped subset: statements, suites, calls, arithmetic and attribute
/// access. This is the grammar the state count in the size report comes from.
pub fn python_subset() -> GrammarBuilder {
    GrammarBuilder::new()
        .name("python-subset")
        .terminal("NEWLINE")
        .terminal("INDENT")
        .terminal("DEDENT")
        .terminal("NAME")
        .terminal("NUMBER")
        .terminal("STRING")
        .terminal("LP")
        .terminal("RP")
        .terminal("LBRACKET")
        .terminal("RBRACKET")
        .terminal("DOT")
        .terminal("COMMA")
        .terminal("COLON")
        .terminal("EQUALS")
        .terminal("PLUS")
        .terminal("MINUS")
        .terminal("STAR")
        .terminal("SLASH")
        .terminal("IF")
        .terminal("ELIF")
        .terminal("ELSE")
        .terminal("WHILE")
        .terminal("FOR")
        .terminal("IN")
        .terminal("DEF")
        .terminal("RETURN")
        .terminal("PASS")
        .terminal("IMPORT")
        .terminal("FROM")
        .terminal("AS")
        .rule("module", &["stmt_list"])
        .rule("stmt_list", &["stmt_list", "stmt"])
        .rule("stmt_list", &["stmt"])
        .rule("stmt", &["simple_stmt"])
        .rule("stmt", &["if_stmt"])
        .rule("stmt", &["while_stmt"])
        .rule("stmt", &["for_stmt"])
        .rule("stmt", &["def_stmt"])
        .rule("simple_stmt", &["expr", "NEWLINE"])
        .rule("simple_stmt", &["NAME", "EQUALS", "expr", "NEWLINE"])
        .rule("simple_stmt", &["RETURN", "NEWLINE"])
        .rule("simple_stmt", &["RETURN", "expr", "NEWLINE"])
        .rule("simple_stmt", &["PASS", "NEWLINE"])
        .rule("simple_stmt", &["IMPORT", "NAME", "NEWLINE"])
        .rule("simple_stmt", &["FROM", "NAME", "IMPORT", "NAME", "NEWLINE"])
        .rule("simple_stmt", &["IMPORT", "NAME", "AS", "NAME", "NEWLINE"])
        .rule("if_stmt", &["IF", "expr", "COLON", "suite"])
        .rule("if_stmt", &["if_stmt", "ELIF", "expr", "COLON", "suite"])
        .rule("if_stmt", &["if_stmt", "ELSE", "COLON", "suite"])
        .rule("while_stmt", &["WHILE", "expr", "COLON", "suite"])
        .rule("for_stmt", &["FOR", "NAME", "IN", "expr", "COLON", "suite"])
        .rule("def_stmt", &["DEF", "NAME", "LP", "params", "RP", "COLON", "suite"])
        .rule("suite", &["NEWLINE", "INDENT", "stmt_list", "DEDENT"])
        .rule("suite", &["simple_stmt"])
        .rule("params", &[])
        .rule("params", &["param_list"])
        .rule("param_list", &["NAME"])
        .rule("param_list", &["param_list", "COMMA", "NAME"])
        .rule("expr", &["term"])
        .rule("expr", &["expr", "PLUS", "term"])
        .rule("expr", &["expr", "MINUS", "term"])
        .rule("term", &["factor"])
        .rule("term", &["term", "STAR", "factor"])
        .rule("term", &["term", "SLASH", "factor"])
        .rule("factor", &["MINUS", "factor"])
        .rule("factor", &["atom"])
        .rule("atom", &["NAME"])
        .rule("atom", &["NUMBER"])
        .rule("atom", &["STRING"])
        .rule("atom", &["LP", "args", "RP"])
        .rule("atom", &["atom", "DOT", "NAME"])
        .rule("atom", &["atom", "LBRACKET", "expr", "RBRACKET"])
        .rule("args", &[])
        .rule("args", &["expr"])
        .rule("args", &["args", "COMMA", "expr"])
}
