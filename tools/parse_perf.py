#!/usr/bin/env python3
"""parse_perf.py — per-file CST parse time on a corpus, against the 3 ms target.

The product's own per-file number (`"micros"` in a build row) is the *record*:
lexer facts, CST parse and facts extraction together. This measures the parse
alone — `rust-graph-deep-scan conformance --reps 1`, one pass over every file —
because that is the quantity the phase-5 target names, and mixing it with the
record would let an extraction change hide a parser regression.

    python3 tools/parse_perf.py                  # measure and report
    python3 tools/parse_perf.py --record         # write the baseline
    python3 tools/parse_perf.py --check          # fail over the p95 limit or the pin

    python3 tools/parse_perf.py --by-lang --docs # one row per language, 3 ms p95 each
    python3 tools/parse_perf.py --by-lang --check

The largest file is reported on its own line: a corpus p95 says nothing about
the file that is five times bigger than the rest, and that file is where a
quadratic shows up first.

`--by-lang` is the phase-6 budget check: the conformance pass names the language
it detected for every file, so one scan of a root prices every language it
holds. A language with fewer than MIN_FILES files is reported and not gated —
a five-file corpus has no p95 worth failing a phase on.
"""
from __future__ import annotations

import argparse
import json
import os
import statistics
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
BASELINE = ROOT / "tools" / "baselines" / "parse_perf_rust.json"
BY_LANG_BASELINE = ROOT / "tools" / "baselines" / "parse_perf_by_lang.json"
DOCS = ROOT / "docs" / "parse-budgets.md"
MIN_FILES = 20
CORPUS = Path(os.environ.get("RG_SWEEP_ROOT", "/tmp/opencode/sweep-local")) / "rust"
SCAN = Path(
    os.environ.get(
        "RG_SCAN",
        "/home/roni/Roni_workspace/rg-kbuilds/release/x86_64-unknown-linux-musl/release/rust-graph-deep-scan",
    )
)
P95_LIMIT_MS = 3.0
# The box runs a fleet of agents, so a single pass measures the scheduler as much
# as the parser. `--reps` keeps the best pass of each file; five is the smallest
# number that made the p95 repeatable across runs (1.5-5.8 ms at one rep).
REPS = 5


def scan_rows(corpus: Path, reps: int = REPS) -> list[dict]:
    result = subprocess.run(
        [str(SCAN), "conformance", str(corpus), "--reps", str(reps)], capture_output=True, text=True
    )
    if result.returncode != 0:
        raise SystemExit(f"parse_perf: conformance exited {result.returncode}: {result.stderr[:200]}")
    rows = []
    for line in result.stdout.splitlines():
        fields = line.split("\t")
        if not fields or fields[0] != "file":
            continue
        row = {"path": fields[1] if len(fields) > 1 else ""}
        for field in fields[2:]:
            if "=" in field:
                key, value = field.split("=", 1)
                row[key] = value
        rows.append(row)
    if not rows:
        raise SystemExit("parse_perf: no file rows in the conformance output")
    return rows


def stats(rows: list[dict]) -> dict:
    times = sorted(float(row["ms"]) for row in rows)
    at = lambda share: times[min(len(times) - 1, int(len(times) * share))]
    biggest = max(rows, key=lambda row: int(row["bytes"]))
    return {
        "files": len(times),
        "mean_ms": round(statistics.fmean(times), 3),
        "p50_ms": round(at(0.50), 3),
        "p95_ms": round(at(0.95), 3),
        "p99_ms": round(at(0.99), 3),
        "max_ms": round(times[-1], 3),
        "largest": {
            "path": biggest["path"].rsplit("/", 1)[-1],
            "bytes": int(biggest["bytes"]),
            "nodes": int(biggest.get("nodes", 0)),
            "ms": round(float(biggest["ms"]), 3),
        },
    }


def measure(corpus: Path) -> dict:
    return stats(scan_rows(corpus))


def measure_by_lang(corpus: Path, reps: int = REPS) -> dict[str, dict]:
    groups: dict[str, list[dict]] = {}
    for row in scan_rows(corpus, reps):
        groups.setdefault(row.get("lang", "unknown"), []).append(row)
    return {lang: stats(rows) for lang, rows in sorted(groups.items())}


def write_docs(table: dict[str, dict], reps: int = REPS) -> None:
    import datetime

    rev = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True)
    today = datetime.date.today().isoformat()
    lines = [
        "# Parse budgets — one row per language",
        "",
        f"Measured {today} at `{rev.stdout.strip() or 'unknown'}`, release build,",
        f"`rust-graph-deep-scan conformance`, best of {reps} pass{'' if reps == 1 else 'es'}, p95 {P95_LIMIT_MS:g} ms per file.",
        "Generated by `tools/parse_perf.py --by-lang --docs`; `--check` fails a language",
        "over the limit or 25% over its pinned p95.",
        "",
        "| language | files | mean | p50 | p95 | p99 | max | largest file |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for lang, row in table.items():
        biggest = row["largest"]
        lines.append(
            f"| {lang} | {row['files']} | {row['mean_ms']} | {row['p50_ms']} | "
            f"{row['p95_ms']} | {row['p99_ms']} | {row['max_ms']} | "
            f"{biggest['path']} ({biggest['bytes']} B, {biggest['ms']} ms) |"
        )
    DOCS.parent.mkdir(parents=True, exist_ok=True)
    DOCS.write_text("\n".join(lines) + "\n")
    print(f"parse_perf: wrote {DOCS.relative_to(ROOT)}")


def main(argv: list[str]) -> int:
    global SCAN
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--corpus", type=Path, default=CORPUS)
    parser.add_argument("--scan", type=Path, default=SCAN)
    parser.add_argument("--record", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--reps", type=int, default=REPS)
    parser.add_argument("--by-lang", action="store_true", help="one row per language instead of one corpus number")
    parser.add_argument("--docs", action="store_true", help="write docs/parse-budgets.md from a --by-lang run")
    parser.add_argument("--json", type=Path)
    parser.add_argument("--from-json", type=Path, help="re-render docs from a saved --by-lang measurement")
    args = parser.parse_args(argv)

    SCAN = args.scan
    if not SCAN.exists():
        print(f"parse_perf: no scan binary at {SCAN}", file=sys.stderr)
        return 2
    if not args.corpus.is_dir():
        print(f"parse_perf: no corpus at {args.corpus}", file=sys.stderr)
        return 2

    if args.by_lang:
        table = json.loads(args.from_json.read_text()) if args.from_json else measure_by_lang(args.corpus, args.reps)
        print(f"{'language':<12}{'files':>7}{'mean':>8}{'p50':>8}{'p95':>8}{'p99':>8}{'max':>8}")
        for lang, row in table.items():
            print(
                f"{lang:<12}{row['files']:>7}{row['mean_ms']:>8}{row['p50_ms']:>8}"
                f"{row['p95_ms']:>8}{row['p99_ms']:>8}{row['max_ms']:>8}"
            )
        if args.json:
            args.json.parent.mkdir(parents=True, exist_ok=True)
            args.json.write_text(json.dumps(table, indent=2) + "\n")
            print(f"parse_perf: wrote {args.json}")
        if args.docs:
            write_docs(table, args.reps)
        if args.record:
            BY_LANG_BASELINE.parent.mkdir(parents=True, exist_ok=True)
            BY_LANG_BASELINE.write_text(json.dumps(table, indent=2) + "\n")
            print(f"parse_perf: wrote {BY_LANG_BASELINE.relative_to(ROOT)}")
        failed = []
        for lang, row in table.items():
            if row["files"] < MIN_FILES:
                continue
            if row["p95_ms"] >= P95_LIMIT_MS:
                failed.append(f"{lang}: p95 {row['p95_ms']} ms is not under {P95_LIMIT_MS} ms")
        if args.check and BY_LANG_BASELINE.exists():
            pinned = json.loads(BY_LANG_BASELINE.read_text())
            for lang, row in table.items():
                if lang in pinned and row["p95_ms"] > pinned[lang]["p95_ms"] * 1.25:
                    failed.append(f"{lang}: p95 {pinned[lang]['p95_ms']} -> {row['p95_ms']} (limit +25%)")
        for line in failed:
            print(f"  {line}", file=sys.stderr)
        return 1 if failed else 0

    now = measure(args.corpus)
    largest = now["largest"]
    print(
        f"parse_perf: {now['files']} files, mean {now['mean_ms']} ms, p50 {now['p50_ms']}, "
        f"p95 {now['p95_ms']}, p99 {now['p99_ms']}, max {now['max_ms']}"
    )
    print(
        f"parse_perf: largest {largest['path']} {largest['bytes']} bytes {largest['nodes']} nodes "
        f"{largest['ms']} ms"
    )
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(now, indent=2) + "\n")
        print(f"parse_perf: wrote {args.json}")

    if args.record:
        BASELINE.parent.mkdir(parents=True, exist_ok=True)
        BASELINE.write_text(json.dumps(now, indent=2) + "\n")
        print(f"parse_perf: wrote {BASELINE.relative_to(ROOT)}")

    failed = []
    if now["p95_ms"] >= P95_LIMIT_MS:
        failed.append(f"p95 {now['p95_ms']} ms is not under {P95_LIMIT_MS} ms")
    if args.check:
        if not BASELINE.exists():
            print(f"parse_perf: no baseline at {BASELINE}; run --record", file=sys.stderr)
            return 2
        pinned = json.loads(BASELINE.read_text())
        for key in ("mean_ms", "p50_ms", "p95_ms", "p99_ms", "max_ms"):
            if key in pinned and now[key] > pinned[key] * 1.25:
                failed.append(f"{key} {pinned[key]} -> {now[key]} (limit +25%)")
    for line in failed:
        print(f"  {line}", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
