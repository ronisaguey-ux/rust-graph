#!/usr/bin/env python3
"""readers_doc.py — write `docs/READERS.md` from the coverage tables.

Each table-driven reader test (`tests/js_coverage.rs`, `tests/ts_coverage.rs`,
`tests/python_coverage.rs`) holds every construct it claims as a row in a
`COVERAGE` array, and every construct it cannot read yet as a row in
`KNOWN_GAPS`. A document typed by hand beside those tables drifts on the first
construct that is added or closed, and a document that overstates coverage is
worse than none, because it is the thing a reader of the repo trusts.

This reads the tables as source and writes the claims, and `--check` exits 1
when the document on disk is not the one the tables describe:

    python3 tools/readers_doc.py            # write docs/READERS.md
    python3 tools/readers_doc.py --check    # fail if the document is stale

The reverse direction — a construct in the document that no test claims — is
checked by `tests/readers_doc.rs`, which reads both sides.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
DOC = ROOT / "docs" / "READERS.md"
TABLES = (
    ("JavaScript", "tests/js_coverage.rs"),
    ("TypeScript", "tests/ts_coverage.rs"),
    ("Python", "tests/python_coverage.rs"),
    ("Rust", "tests/rust_coverage.rs"),
)
PROSE = (
    (
        "Go and Java",
        "tests/facts_go_java.rs",
        "the facts a Go or Java file must produce, asserted by named tests",
    ),
)

TUPLE_START = re.compile(r"\(\s*\"((?:[^\"\\]|\\.)*)\"", re.S)


def unescape(text: str) -> str:
    return text.encode().decode("unicode_escape")


def block(source: str, name: str) -> str | None:
    marker = f"const {name}:"
    start = source.find(marker)
    if start < 0:
        return None
    end = source.find("\n];", start)
    if end < 0:
        return None
    return source[start:end]


def constructs(path: Path, name: str) -> list[str]:
    source = (ROOT / path).read_text()
    body = block(source, name)
    if body is None:
        return []
    return [unescape(match.group(1)) for match in TUPLE_START.finditer(body)]


def render() -> str:
    lines = [
        "# Readers — what each one claims",
        "",
        "Two readers read a source file: the one-pass lexer, and the CST reader behind",
        "`--deep`. A construct is *covered* when both readers produce the same facts and",
        "the guard has nothing to fall back for; a construct in the gap list is asserted",
        "*to disagree*, so closing it without moving the row fails the suite.",
        "",
        "This file is generated by `tools/readers_doc.py` from the coverage tables in",
        "`tests/`. `tests/readers_doc.rs` checks it in both directions: every construct a",
        "test claims is listed here, and every listed construct is claimed by a test.",
        "",
    ]
    for language, path in TABLES:
        covered = constructs(Path(path), "COVERAGE")
        gaps = constructs(Path(path), "KNOWN_GAPS")
        lines += [f"## {language} — `{path}`", "", f"Covered ({len(covered)}):", ""]
        lines += [f"- {name}" for name in covered] or ["- nothing claimed yet"]
        lines += ["", f"Known gaps ({len(gaps)}):", ""]
        lines += [f"- {name}" for name in gaps] or ["- none: every construct the table claims reads the same on both paths"]
        lines.append("")
    lines += ["## Languages claimed by named tests", ""]
    lines += [f"- **{language}** (`{path}`): {claim}." for language, path, claim in PROSE]
    lines += [
        "",
        "## What neither reader claims",
        "",
        "The other languages in the 45-language corpus have a one-pass reader only; their",
        "files carry no CST facts and cannot fall back, because nothing is compared. See",
        "`docs/corpus45-table.md`, which is generated from the corpus by",
        "`tools/corpus_table.py`.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not DOC.exists() or DOC.read_text() != text:
            print(f"readers_doc: {DOC} is stale; run tools/readers_doc.py", file=sys.stderr)
            return 1
        print(f"readers_doc: {DOC} matches the coverage tables")
        return 0
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(text)
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
